# shellcheck shell=bash
# Wire credentials pulled from SSM Parameter Store at RUNTIME — nothing is baked into any
# committed file. Values are never echoed or logged (type/presence only). Sets the git
# identity, authenticates gh, writes the Snowflake key to a 0600 file on the volume, and
# builds the 0600 feedback-loop env file the systemd service sources.
#
# The one interactive credential (`claude login`) is NOT here — it is the login phase.
section "secrets from SSM"
require_root

SECRETS_DIR="${SRA_DATA_MOUNT}/secrets"
install -d -m 700 -o "${SRA_TARGET_USER}" -g "${SRA_TARGET_USER}" "$SECRETS_DIR"

# --- git identity (non-secret; set directly). ---------------------------------------
if [ -n "${SRA_GIT_EMAIL}" ] && [ -n "${SRA_GIT_NAME}" ]; then
  step "git identity -> ${SRA_GIT_NAME} <${SRA_GIT_EMAIL}>"
  run_as_user "git config --global user.email '${SRA_GIT_EMAIL}'"
  run_as_user "git config --global user.name '${SRA_GIT_NAME}'"
else
  warn "SRA_GIT_EMAIL/SRA_GIT_NAME unset — skipping git identity (set them per box)"
fi

# --- GitHub token -> gh auth (drives clone/commit over HTTPS via gh's credential helper).
GH_TOKEN="$(ssm_fetch "${SRA_SSM_PREFIX}/github/token" yes || true)"
if ssm_value_ok "$GH_TOKEN"; then
  step "authenticating gh with the GitHub token"
  # Pipe the token via stdin (never on the command line -> not visible in ps).
  printf '%s' "$GH_TOKEN" | runuser -l "${SRA_TARGET_USER}" -c 'gh auth login --with-token' \
    && runuser -l "${SRA_TARGET_USER}" -c 'gh auth setup-git' \
    && ok "gh authenticated + git credential helper wired"
else
  warn "github/token SSM param unset — gh not authenticated; private clone/push will fail until set"
fi
unset GH_TOKEN

# --- Snowflake private key (SecureString) -> 0600 file on the volume. ----------------
SF_KEY="$(ssm_fetch "${SRA_SSM_PREFIX}/snowflake/private-key-b64" yes || true)"
KEY_PATH="${SECRETS_DIR}/snowflake_key.p8.b64"
if ssm_value_ok "$SF_KEY"; then
  printf '%s' "$SF_KEY" >"$KEY_PATH"
  chmod 600 "$KEY_PATH"; chown "${SRA_TARGET_USER}:${SRA_TARGET_USER}" "$KEY_PATH"
  ok "wrote Snowflake private key -> ${KEY_PATH} (mode 600)"
else
  warn "snowflake/private-key-b64 unset — the feedback read will fail auth until set"
fi
unset SF_KEY

# --- The feedback-loop env file (0600, owned by sra). Sourced when the loop is run on
#     demand (there is no scheduled unit). Mirrors the Mac launchd env for
#     scripts/sra_feedback_loop_daily: Hermes home + worker runtime + Slack + Snowflake.
ENV_FILE="${SECRETS_DIR}/feedback-loop.env"
umask 077
{
  echo "# Generated by config/secrets.sh — do not commit. Secrets pulled from SSM at setup time."
  echo "SRA_HERMES_HOME=${SRA_DATA_MOUNT}/state/hermes"
  echo "SR_WORKER_RUNTIME=claude"
  if [ -n "${SRA_FEEDBACK_LOOP_SLACK_CHANNEL:-}" ]; then echo "SRA_FEEDBACK_LOOP_SLACK_CHANNEL=${SRA_FEEDBACK_LOOP_SLACK_CHANNEL}"; fi
  echo "SNOWFLAKE_PRIVATE_KEY_PATH=${KEY_PATH}"
  echo "SRA_AWS_REGION=${SRA_REGION}"

  SLACK_BOT_TOKEN="$(ssm_fetch "${SRA_SSM_PREFIX}/slack/bot-token" yes || true)"
  if ssm_value_ok "$SLACK_BOT_TOKEN"; then echo "SLACK_BOT_TOKEN=${SLACK_BOT_TOKEN}"; fi

  OPENROUTER_API_KEY="$(ssm_fetch "${SRA_SSM_PREFIX}/openrouter/api-key" yes || true)"
  if ssm_value_ok "$OPENROUTER_API_KEY"; then echo "OPENROUTER_API_KEY=${OPENROUTER_API_KEY}"; fi

  # Snowflake connection identity (non-secret SF_* block) appended verbatim if present.
  SF_IDENTITY="$(ssm_fetch "${SRA_SSM_PREFIX}/snowflake/identity" no || true)"
  if ssm_value_ok "$SF_IDENTITY"; then printf '%s\n' "$SF_IDENTITY"; fi
} >"$ENV_FILE"
chmod 600 "$ENV_FILE"; chown "${SRA_TARGET_USER}:${SRA_TARGET_USER}" "$ENV_FILE"
umask 022
install -d -o "${SRA_TARGET_USER}" -g "${SRA_TARGET_USER}" "${SRA_DATA_MOUNT}/state/hermes"
ok "wrote ${ENV_FILE} (mode 600)"

# --- circli runtime token (CircleCI). Written to the loop env for circli to consume. --
# circli authenticates via keyring by default; on a headless box that needs a backend, so
# we ALSO surface the token as CIRCLECI_TOKEN in the env file. Exact circli wiring is a
# check-in item (see README).
CIRCLECI_TOKEN="$(ssm_fetch "${SRA_SSM_PREFIX}/circleci/token" yes || true)"
if ssm_value_ok "$CIRCLECI_TOKEN"; then
  printf 'CIRCLECI_TOKEN=%s\n' "$CIRCLECI_TOKEN" >>"$ENV_FILE"
  ok "added CIRCLECI_TOKEN to the loop env"
else
  warn "circleci/token unset — circli will be unauthenticated until set"
fi
unset CIRCLECI_TOKEN SLACK_BOT_TOKEN OPENROUTER_API_KEY SF_IDENTITY