# shellcheck shell=bash
# Put every heavy tree on the durable data volume, not the ~7 G root. Creates the
# directory layout under ${SRA_DATA_MOUNT} and writes an environment file the target
# user's shell + the systemd services source, so npm-global, uv/npm/pip/mise caches,
# worktrees, and the repo all land on the volume BY CONSTRUCTION — not by remembering a
# flag at each install. Runs before mise/agents so their first install already lands right.
section "data-volume storage layout"
require_root
mountpoint -q "${SRA_DATA_MOUNT}" || die "${SRA_DATA_MOUNT} is not mounted"

# Directory layout on the volume.
DIRS=(
  "${SRA_DATA_MOUNT}/work"
  "${SRA_DATA_MOUNT}/worktrees"
  "${SRA_DATA_MOUNT}/logs"
  "${SRA_DATA_MOUNT}/state"
  "${SRA_DATA_MOUNT}/npm-global"
  "${SRA_DATA_MOUNT}/caches/npm"
  "${SRA_DATA_MOUNT}/caches/uv"
  "${SRA_DATA_MOUNT}/caches/pip"
  "${SRA_DATA_MOUNT}/caches/mise"
  "${SRA_DATA_MOUNT}/caches/xdg"
)
for d in "${DIRS[@]}"; do install -d -o "${SRA_TARGET_USER}" -g "${SRA_TARGET_USER}" "$d"; done
# Reconcile ownership on re-run: the durable volume can carry stale content owned by a
# different user (e.g. an earlier bootstrap run as `ubuntu`). Force the tool-writable
# trees to the target user so npm / uv / mise can write regardless of that history —
# without this a pre-existing root/ubuntu-owned node_modules subdir fails with EACCES.
chown -R "${SRA_TARGET_USER}:${SRA_TARGET_USER}" "${SRA_DATA_MOUNT}/npm-global" "${SRA_DATA_MOUNT}/caches" 2>/dev/null || true
# secrets/ is 0700 (holds the Snowflake key + env files written by the secrets phase).
install -d -m 700 -o "${SRA_TARGET_USER}" -g "${SRA_TARGET_USER}" "${SRA_DATA_MOUNT}/secrets"
ok "created directory layout under ${SRA_DATA_MOUNT}"

# The environment file the user's shell sources. Written to the volume; symlinked into
# the home dir profile so both interactive shells and `mise exec` see it.
ENV_SNIPPET="${SRA_DATA_MOUNT}/state/sra-env.sh"
cat > "$ENV_SNIPPET" <<ENV
# Generated by config/storage.sh — puts caches / global installs on the data volume.
export XDG_CACHE_HOME="${SRA_DATA_MOUNT}/caches/xdg"
export NPM_CONFIG_PREFIX="${SRA_DATA_MOUNT}/npm-global"
export NPM_CONFIG_CACHE="${SRA_DATA_MOUNT}/caches/npm"
export UV_CACHE_DIR="${SRA_DATA_MOUNT}/caches/uv"
export PIP_CACHE_DIR="${SRA_DATA_MOUNT}/caches/pip"
export MISE_CACHE_DIR="${SRA_DATA_MOUNT}/caches/mise"
export PATH="${SRA_DATA_MOUNT}/npm-global/bin:\$HOME/.local/bin:\$PATH"
ENV
chown "${SRA_TARGET_USER}:${SRA_TARGET_USER}" "$ENV_SNIPPET"
chmod 0644 "$ENV_SNIPPET"
ok "wrote ${ENV_SNIPPET}"

# Source it from .bashrc once (idempotent). Sourcing from the volume means later edits
# to the snippet take effect without re-touching .bashrc.
BASHRC="${SRA_TARGET_HOME}/.bashrc"
if ! grep -qsF "$ENV_SNIPPET" "$BASHRC" 2>/dev/null; then
  printf '\n# sra data-volume environment\n[ -f "%s" ] && source "%s"\n' "$ENV_SNIPPET" "$ENV_SNIPPET" >>"$BASHRC"
  chown "${SRA_TARGET_USER}:${SRA_TARGET_USER}" "$BASHRC"
  ok "sourced ${ENV_SNIPPET} from ${BASHRC}"
fi