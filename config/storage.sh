# shellcheck shell=bash
# Put every heavy tree on the durable data volume, not the small root. Single-user model:
# the config user owns the mount and its trees (no ownership reconciliation). Writes the
# orb-env.sh snippet (caches + npm-global on the volume, mise shims on PATH) — sourced by the
# login shells AND by setup.sh after each phase, so the non-interactive install phases inherit
# it (design S-storage: option A, omarchy keeps install-time env in the driver).
section "data-volume storage layout"
mountpoint -q "$ORB_BOX_DATA_MOUNT" || die "${ORB_BOX_DATA_MOUNT} is not mounted"

# Own the mount for the config user (idempotent; a freshly-formatted volume is root-owned).
as_root chown "$(id -un):$(id -gn)" "$ORB_BOX_DATA_MOUNT"

DIRS=(
  "${ORB_BOX_DATA_MOUNT}/dev" "${ORB_BOX_DATA_MOUNT}/worktrees" "${ORB_BOX_DATA_MOUNT}/logs"
  "${ORB_BOX_DATA_MOUNT}/state" "${ORB_BOX_DATA_MOUNT}/npm-global"
  "${ORB_BOX_DATA_MOUNT}/caches/npm" "${ORB_BOX_DATA_MOUNT}/caches/uv"
  "${ORB_BOX_DATA_MOUNT}/caches/pip" "${ORB_BOX_DATA_MOUNT}/caches/mise"
  "${ORB_BOX_DATA_MOUNT}/caches/xdg" "${ORB_BOX_DATA_MOUNT}/mise"
  "${ORB_BOX_DATA_MOUNT}/uv/tools" "${ORB_BOX_DATA_MOUNT}/uv/bin"
)
for d in "${DIRS[@]}"; do mkdir -p "$d"; done
install -d -m 700 "${ORB_BOX_DATA_MOUNT}/secrets"
ok "created directory layout under ${ORB_BOX_DATA_MOUNT}"

# Repos live at ~/dev/<repo> — identical to the Mac, so paths line up both sides — but
# backed by the durable volume via this symlink, keeping heavy trees off the small root.
# Idempotent; never clobbers a real ~/dev directory (only manages the symlink).
DEV_LINK="${HOME}/dev"
DEV_TARGET="${ORB_BOX_DATA_MOUNT}/dev"
if [ -L "$DEV_LINK" ]; then
  [ "$(readlink "$DEV_LINK")" = "$DEV_TARGET" ] || { rm "$DEV_LINK"; ln -s "$DEV_TARGET" "$DEV_LINK"; }
  ok "${DEV_LINK} -> ${DEV_TARGET}"
elif [ -e "$DEV_LINK" ]; then
  warn "${DEV_LINK} exists and is not a symlink — leaving it (repos won't be volume-backed via ${DEV_LINK})"
else
  ln -s "$DEV_TARGET" "$DEV_LINK"
  ok "${DEV_LINK} -> ${DEV_TARGET}"
fi

ENV_SNIPPET="${ORB_BOX_DATA_MOUNT}/state/orb-env.sh"
cat > "$ENV_SNIPPET" <<ENV
# Generated by orb config/storage.sh — caches + global installs on the data volume, and mise
# shims on PATH so node/python/uv + the CLI toolkit resolve in ANY shell (interactive or not).
export XDG_CACHE_HOME="${ORB_BOX_DATA_MOUNT}/caches/xdg"
export NPM_CONFIG_PREFIX="${ORB_BOX_DATA_MOUNT}/npm-global"
export NPM_CONFIG_CACHE="${ORB_BOX_DATA_MOUNT}/caches/npm"
export UV_CACHE_DIR="${ORB_BOX_DATA_MOUNT}/caches/uv"
export UV_TOOL_DIR="${ORB_BOX_DATA_MOUNT}/uv/tools"  # \`uv tool install\` CLIs on the volume, not the root
export UV_TOOL_BIN_DIR="${ORB_BOX_DATA_MOUNT}/uv/bin" # ...same filesystem as UV_CACHE_DIR, so uv hardlinks (no cross-device copy warning)
export PIP_CACHE_DIR="${ORB_BOX_DATA_MOUNT}/caches/pip"
export MISE_CACHE_DIR="${ORB_BOX_DATA_MOUNT}/caches/mise"
export MISE_DATA_DIR="${ORB_BOX_DATA_MOUNT}/mise"  # tool installs (node/python/toolkit) on the volume, not the 7G root
export PATH="${ORB_BOX_DATA_MOUNT}/mise/shims:${ORB_BOX_DATA_MOUNT}/npm-global/bin:${ORB_BOX_DATA_MOUNT}/uv/bin:\$HOME/.local/bin:\$PATH"
ENV
ok "wrote ${ENV_SNIPPET}"

for rc in "${HOME}/.bashrc" "${HOME}/.profile"; do
  ensure_line "$rc" "[ -f \"${ENV_SNIPPET}\" ] && . \"${ENV_SNIPPET}\""
done
ok "sourced ${ENV_SNIPPET} from .bashrc + .profile"

# The rc files above cover login/interactive shells only. A bare `ssh box '<cmd>'` (non-login,
# non-interactive — automation, push-to-vm) sources neither, so the toolchain would be missing;
# worse, a shim on PATH without MISE_DATA_DIR makes mise reinstall onto the small root disk.
# /etc/environment is the one place PAM applies to EVERY session type, so project the same env
# there too. Static KEY=VALUE (no shell expansion), hence absolute values; overwrite each run
# (idempotent). BASH_ENV was tried first but bash 5.2 ignores it for `bash -c` (how sshd runs
# remote commands), so it cannot carry this.
SYSTEM_PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/usr/games:/usr/local/games:/snap/bin"
as_root tee /etc/environment >/dev/null <<ETCENV
PATH="${ORB_BOX_DATA_MOUNT}/mise/shims:${ORB_BOX_DATA_MOUNT}/npm-global/bin:${ORB_BOX_DATA_MOUNT}/uv/bin:${HOME}/.local/bin:${SYSTEM_PATH}"
MISE_DATA_DIR="${ORB_BOX_DATA_MOUNT}/mise"
MISE_CACHE_DIR="${ORB_BOX_DATA_MOUNT}/caches/mise"
XDG_CACHE_HOME="${ORB_BOX_DATA_MOUNT}/caches/xdg"
NPM_CONFIG_PREFIX="${ORB_BOX_DATA_MOUNT}/npm-global"
NPM_CONFIG_CACHE="${ORB_BOX_DATA_MOUNT}/caches/npm"
UV_CACHE_DIR="${ORB_BOX_DATA_MOUNT}/caches/uv"
UV_TOOL_DIR="${ORB_BOX_DATA_MOUNT}/uv/tools"
UV_TOOL_BIN_DIR="${ORB_BOX_DATA_MOUNT}/uv/bin"
PIP_CACHE_DIR="${ORB_BOX_DATA_MOUNT}/caches/pip"
ETCENV
ok "wrote /etc/environment (toolchain env for non-login shells)"
